/**
 * Раздача ширины при перетаскивании границы колонки.
 *
 * ПОЧЕМУ ОТДЕЛЬНЫЙ МОДУЛЬ. Правило чисто арифметическое, а живёт оно внутри обработчика
 * pointermove, где его не проверить: там DOM, курсор и подписки. Здесь — функция, которую
 * читает тест.
 *
 * ПРАВИЛО СУЖЕНИЯ. Границу тянут ВЛЕВО — колонка сужается до своей минимальной ширины, а
 * дальше сужается ПРЕДЫДУЩАЯ по тому же правилу, потом та, что перед ней, и так до первой.
 * Прежде движение просто упиралось в минимум: таблица из десяти колонок не помещалась в
 * узкий пейн, а подвинуть границу дальше было нельзя — оставалось прятать колонки
 * настройкой. Теперь граница едет дальше, забирая место у левых соседей.
 *
 * ПРАВИЛО РАСШИРЕНИЯ. Границу тянут ВПРАВО — растёт ТОЛЬКО та колонка, за чью границу
 * держатся, то есть соседняя слева от схваченного края. Соседей это не касается вовсе:
 * человек просит места ЭТОЙ колонке, а не перекладывает его по таблице.
 *
 * Сужение и расширение намеренно НЕ зеркальны. Сужение идёт цепочкой, потому что иначе
 * движение упирается в минимум и таблицу не сжать; расширение упереться не может — справа
 * всегда есть куда расти, и забирать место у соседей незачем. Обратный ход «вернуть
 * отнятое» здесь пробовался и убран: он делал простое движение мышью непредсказуемым —
 * граница ехала вправо, а менялись ширины колонок, которых человек не трогал.
 *
 * Колонка отметок (чекбоксы) в раздаче не участвует вовсе: её здесь нет — вызывающий
 * передаёт только колонки данных. Ширина отметок постоянная, и отдавать её под данные
 * значило бы сделать чекбоксы недоступными ради лишних десяти пикселей.
 */
export type ResizeColumn = {
	/** Текущая ширина, px — на момент начала перетаскивания. */
	width: number;
	/** Минимальная ширина, px: ниже неё колонка не сжимается. */
	min: number;
};

/**
 * Новые ширины колонок после сдвига границы колонки `index` на `delta` пикселей.
 *
 * Возвращает массив той же длины: колонки, которых сдвиг не коснулся, сохраняют ширину.
 */
export function spreadResize(columns: ResizeColumn[], index: number, delta: number): number[] {
	const out = columns.map((c) => c.width);
	if (index < 0 || index >= columns.length) return out;

	// Вправо — растёт только схваченная колонка: соседи остаются как были.
	if (delta >= 0) {
		out[index] = columns[index].width + delta;
		return out;
	}

	// Сужение: забираем недостающее сперва у самой колонки, потом у левых соседей.
	let need = -delta;
	for (let i = index; i >= 0 && need > 0; i -= 1) {
		const room = Math.max(0, columns[i].width - columns[i].min);
		const take = Math.min(need, room);
		if (take > 0) {
			out[i] = columns[i].width - take;
			need -= take;
		}
	}
	return out;
}

/**
 * Ширина колонки по самому длинному значению в ней — «автоподбор», который в таблицах
 * вызывают двойным щелчком по границе заголовка.
 *
 * ЗАЧЕМ. Подгонять границу мышью под самое длинное значение — работа на несколько попыток:
 * длинное значение может быть и не видно, если оно ниже по списку. Двойной щелчок делает это
 * за один раз, и ровно так же он работает в любой другой таблице, которую человек видел.
 *
 * ЧТО ИЗМЕРЯЕТСЯ. Содержимое ячеек ВИДИМЫХ строк и сам заголовок: колонка, в которую не
 * помещается её же название, выглядит сломанной. Отступы ячейки прибавляются здесь, а не в
 * измерении, — замеряется содержимое, а не коробка.
 *
 * ПРЕДЕЛЫ. Ниже минимума колонки не опускаемся (иначе автоподбор прятал бы данные), выше
 * `max` не поднимаемся: одна ячейка с длинным примечанием не должна выдавливать за край всё
 * остальное. `max` задаёт вызывающий — это ширина, дальше которой таблице расти некуда.
 */
export function autoFitWidth(input: {
	/** Ширины содержимого ячеек колонки, px (включая скрытое за многоточием). */
	contents: number[];
	/** Ширина содержимого заголовка, px: название колонки тоже обязано помещаться. */
	header?: number;
	/** Горизонтальные отступы ячейки и запас на бордюр, px. */
	padding?: number;
	min: number;
	max: number;
}): number {
	const { contents, header = 0, padding = 0, min, max } = input;
	const widest = Math.max(header, ...contents, 0);
	// Пустая колонка (ни значений, ни заголовка) — это не повод схлопнуть её в ноль.
	const wanted = Math.ceil(widest + padding);
	return Math.min(Math.max(wanted, min), Math.max(min, max));
}
