// Порядок вкладок панелей — по последней активации.
//
// Активная вкладка стоит первой, прежняя первая — второй и так далее: человек ищет то,
// с чем работает, в начале ряда, а не там, где эта панель когда-то открылась. Второе:
// при нехватке ширины лишние вкладки уезжают в «ещё», и в порядке открытия туда могла
// уехать ТЕКУЩАЯ панель — вкладка активной панели пропадала с глаз.
//
// Порядок хранится списком идентификаторов ОТДЕЛЬНО от массива панелей (см. App). Сам
// массив не переставляется намеренно: вместе с ним переехал бы DOM пейнов, а переезд узла
// сбрасывает прокрутку внутри — переключение вкладок отматывало бы таблицы к началу.

/**
 * Активированная вкладка — в начало ряда; прежняя первая становится второй, остальные
 * сохраняют свой порядок. Уже стоящая первой не двигается: новый массив заставил бы ряд
 * вкладок перерисовываться на каждый щелчок по текущей вкладке.
 */
export function promotePaneOrder(order: string[], uniqId: string): string[] {
	if (order[0] === uniqId) return order;
	return [uniqId, ...order.filter((id) => id !== uniqId)];
}

/** Панели в порядке вкладок: сначала те, что в списке порядка, затем всё остальное. */
export function orderPanes<T extends { uniqId: string }>(panes: T[], order: readonly string[]): T[] {
	if (order.length === 0 || panes.length < 2) return panes;
	const rank = new Map(order.map((id, i) => [id, i]));
	// Панель, которой нет в списке порядка (успела появиться раньше, чем он обновился),
	// уходит в конец — сортировка устойчивая, и между собой такие сохраняют свой порядок.
	const rankOf = (p: T) => rank.get(p.uniqId) ?? Number.MAX_SAFE_INTEGER;
	return [...panes].sort((a, b) => rankOf(a) - rankOf(b));
}
