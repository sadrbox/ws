/**
 * ЕДИНЫЙ QueryClient приложения — как модуль, а не как состояние компонента.
 *
 * ЗАЧЕМ ОТДЕЛЬНЫМ МОДУЛЕМ. Обновлять данные после выполненной команды должен тот, кто
 * знает, что команда выполнилась, — реестр операций (models/OneCAdmin/progress). Он живёт
 * ВНЕ дерева React: операция переживает закрытие карточки, с которой её запустили, и
 * переключение вкладок. Пока клиент создавался внутри App, дотянуться до него можно было
 * только из смонтированного компонента — и обновление получали лишь те экраны, которые
 * сами за этим следили. Открытая карточка базы после публикации показывала прежнее
 * состояние до перезагрузки страницы.
 *
 * Экземпляр один на вкладку браузера: кэш запросов общий для всех панелей, и второй клиент
 * означал бы вторую, расходящуюся с первой, копию данных.
 */
import { QueryClient } from "@tanstack/react-query";

export const queryClient = new QueryClient({
	defaultOptions: {
		queries: {
			// offlineFirst: при отсутствии сети — сначала отдать данные из кэша,
			// а сетевой запрос выполнить позже, когда сеть восстановится.
			networkMode: "offlineFirst",
			staleTime: 2 * 60 * 1000,
			gcTime: 30 * 60 * 1000,
			retry: (failureCount, error: { code?: string; message?: string; status?: number }) => {
				// Не ретраить при сетевых ошибках — бессмысленно
				if (error?.code === "ERR_NETWORK" || error?.message === "Network Error") return false;
				// 4xx — отказ по существу (нет прав, не аутентифицирован, неверный вход), а не
				// сбой связи: повтор даст тот же ответ. Для команд в 1С это ещё и цена —
				// второй вызов rac и второй сеанс ради того же отказа.
				if (typeof error?.status === "number" && error.status >= 400 && error.status < 500) return false;
				return failureCount < 1;
			},
		},
		mutations: {
			networkMode: "offlineFirst",
		},
	},
});

export default queryClient;
