// ─────────────────────────────────────────────────────────────────────────────
// SheetJS (xlsx) — ТОЛЬКО ПО ТРЕБОВАНИЮ (аудит 26.09, О2).
//
// Библиотека весит 420 КБ (138 КБ gzip). Статический `import * as XLSX` в печатной
// панели, панели отчёта и выгрузке накладной тянул её при открытии 22 документов и
// списков и всех отчётов, хотя нужна она только в момент выгрузки или загрузки файла.
// Поэтому модули берут её здесь, внутри обработчика: `const XLSX = await loadXlsx()`.
// Типы (WorkBook и т. п.) импортируются как `import type` — они стираются при сборке.
// ─────────────────────────────────────────────────────────────────────────────
//
// Проверить потом: стоит xlsx 0.18.5 — последняя версия SheetJS в реестре npm, с известными
// уязвимостями при разборе чужих файлов (CVE-2023-30533 — исправлена в 0.19.3, CVE-2024-22363
// — в 0.20.2); а ею читаются файлы, которые загружают пользователи (импорт цен, номенклатуры,
// выписок КН). Актуальная 0.20.3 распространяется только тарболлом с https://cdn.sheetjs.com
// (не из реестра npm) — замену зависимости на внешний тарболл решает владелец. API тот же:
// read/write/writeFile/utils, правки кода не нужны.
export type XlsxModule = typeof import("xlsx");

export function loadXlsx(): Promise<XlsxModule> {
	return import("xlsx");
}
