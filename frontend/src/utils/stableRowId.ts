/**
 * НОМЕР СТРОКИ — ИЗ ЕЁ ПОСТОЯННОГО КЛЮЧА, а не из порядка в ответе.
 *
 * ЖИВОЙ СЛУЧАЙ (17.09). В «Базах», «Сеансах» и «Соединениях» `id` строки был её номером по порядку. Строка исчезла
 * (сняли сеанс, убрали базу) — номера сдвинулись, и всё, что панель помнит по номеру, поехало на соседнюю строку:
 * отметки, активная строка, подсветка «показать в списке». Отметки уже переносит сама таблица (Table.remapSelection),
 * но это лечение следствия: пока номер зависит от порядка, каждое перечитывание списка меняет личность строк.
 *
 * Здесь номер считается из ключа (`uuid` сеанса, `pid` процесса, ключ базы): тот же ключ — тот же номер, пока строка
 * жива, независимо от того, сколько строк ушло выше неё.
 *
 * ПОЧЕМУ ЧИСЛО, А НЕ СТРОКА. `TDataItem.id` числовой, и на нём держатся выделение, навигация и курсорная подгрузка;
 * менять его тип — переписывать таблицу целиком. Хватает 31 бита: столкновения разводятся при раздаче (см. ниже).
 */

/** FNV-1a, 32 бита → положительное целое. Не криптография: нужна устойчивость, а не стойкость. */
export function stableRowId(key: string): number {
	let h = 0x811c9dc5;
	for (let i = 0; i < key.length; i++) {
		h ^= key.charCodeAt(i);
		h = Math.imul(h, 0x01000193);
	}
	// Ноль — «нет строки» во многих проверках, поэтому его не выдаём.
	return (h & 0x7fffffff) || 1;
}

/**
 * Раздать строкам номера по их ключам. Столкновение (два разных ключа дали одно число) разводится следующим
 * свободным номером: одинаковые номера — это одна строка вместо двух, и React, и выделение считают их одной.
 */
export function withStableIds<T>(items: readonly T[], keyOf: (item: T, index: number) => string): (T & { id: number })[] {
	const taken = new Set<number>();
	return items.map((item, index) => {
		let id = stableRowId(keyOf(item, index) || String(index));
		while (taken.has(id)) id = (id % 0x7fffffff) + 1;
		taken.add(id);
		return { ...item, id };
	});
}
