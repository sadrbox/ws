/**
 * Ширина колонок при перетаскивании границы (ResizeHandle).
 *
 * ПРАВИЛО. Влево — колонка сужается до своего минимума, а дальше место отдаёт ПРЕДЫДУЩАЯ,
 * за ней та, что перед ней, и так до первой. Вправо — ТОЧНЫЙ ОБРАТНЫЙ ХОД: сперва место
 * возвращается тем, у кого его забрали (слева направо, каждому до его прежней ширины), и
 * только потом растёт сама колонка.
 *
 * ЗАЧЕМ ЭТО НУЖНО. Раньше движение просто упиралось в минимум: таблица из десяти колонок в
 * узком пейне не помещалась, а подвинуть границу было некуда — оставалось прятать колонки
 * настройкой. А без обратного хода движение туда-обратно не возвращало бы таблицу в
 * прежний вид: ужатые соседи оставались бы на минимумах, а место доставалось бы одной
 * колонке.
 *
 * КОЛОНКА ОТМЕТОК СЮДА НЕ ПОПАДАЕТ ВОВСЕ: расчёт получает только колонки данных, а ширина
 * чекбоксов постоянна — отдавать её под данные значило бы сделать отметки недоступными.
 */
import { describe, it, expect } from "vitest";
import { spreadResize, type ResizeColumn } from "src/components/Table/columnResize";

/** Три колонки по 200px с минимумом 100px: запас у каждой ровно 100, долгов ни у кого. */
const cols = (): ResizeColumn[] => ([
	{ width: 200, min: 100, base: 200 },
	{ width: 200, min: 100, base: 200 },
	{ width: 200, min: 100, base: 200 },
]);

describe("ширина колонок: раздача при перетаскивании границы", () => {
	it("вправо растёт сама колонка, когда возвращать соседям нечего", () => {
		expect(spreadResize(cols(), 1, 50)).toEqual([200, 250, 200]);
	});

	it("влево сужается сама колонка, пока у неё есть запас", () => {
		expect(spreadResize(cols(), 2, -60)).toEqual([200, 200, 140]);
	});

	it("дойдя до минимума, колонка отдаёт остаток предыдущей", () => {
		// 140 нужно: 100 берём у самой (200 → 100, это её минимум), остальные 40 — у левой.
		expect(spreadResize(cols(), 2, -140)).toEqual([200, 160, 100]);
	});

	it("цепочка доходит до первой колонки", () => {
		// 250: по 100 у третьей и второй, оставшиеся 50 — у первой.
		expect(spreadResize(cols(), 2, -250)).toEqual([150, 100, 100]);
	});

	it("когда запаса не осталось нигде, движение останавливается на минимумах", () => {
		// Просят 400 при общем запасе 300 — больше отдать нечего, и ничего не ломается.
		expect(spreadResize(cols(), 2, -400)).toEqual([100, 100, 100]);
	});

	it("у первой колонки отбирать не у кого — она просто упирается в минимум", () => {
		expect(spreadResize(cols(), 0, -500)).toEqual([100, 200, 200]);
	});

	it("колонка без запаса сразу передаёт сужение соседке слева", () => {
		const tight: ResizeColumn[] = [
			{ width: 200, min: 100, base: 200 },
			{ width: 100, min: 100, base: 100 },
		];
		expect(spreadResize(tight, 1, -30)).toEqual([170, 100]);
	});
});

// ── Обратный ход: расширение сперва отдаёт долги ────────────────────────────
//
// Состояние после сужения: первые две колонки ужаты до минимума, у каждой помнится прежняя
// ширина (base). Тянем границу третьей вправо — место обязано вернуться тем, у кого его
// забрали, и в обратном порядке: слева направо.

describe("ширина колонок: расширение возвращает отнятое", () => {
	/** Две ужатые колонки (100 из 200) и третья, которую тянут. */
	const debts = (): ResizeColumn[] => ([
		{ width: 100, min: 100, base: 200 },
		{ width: 100, min: 100, base: 200 },
		{ width: 100, min: 100, base: 100 },
	]);

	it("первой возвращается ПЕРВАЯ колонка, а не та, что ближе", () => {
		expect(spreadResize(debts(), 2, 60)).toEqual([160, 100, 100]);
	});

	it("вернув первой всё, переходим ко второй", () => {
		// 160: сто первой (100 → 200, её прежняя ширина) и шестьдесят второй.
		expect(spreadResize(debts(), 2, 160)).toEqual([200, 160, 100]);
	});

	it("когда долгов не осталось, растёт сама колонка", () => {
		// 250: по сто обеим ужатым, оставшиеся пятьдесят — третьей.
		expect(spreadResize(debts(), 2, 250)).toEqual([200, 200, 150]);
	});

	it("колонку не расширяют сверх её прежней ширины за чужой счёт", () => {
		// Долг перед первой — ровно 100; больше ей не достаётся ни при каком размахе.
		expect(spreadResize(debts(), 2, 1000)[0]).toBe(200);
	});

	it("ужатая колонка возвращает себе своё, если тянут ЕЁ границу", () => {
		// Тянут первую: она и есть «текущая», и долг перед ней возвращается ей же.
		expect(spreadResize(debts(), 0, 40)).toEqual([140, 100, 100]);
	});

	it("движение туда-обратно возвращает таблицу в прежний вид", () => {
		const start = cols();
		const shrunk = spreadResize(start, 2, -250);
		expect(shrunk).toEqual([150, 100, 100]);
		// Память о прежних ширинах — то, что при сужении сохраняет TableHeader (baseWidth).
		const remembered: ResizeColumn[] = start.map((c, i) => ({
			width: shrunk[i], min: c.min, base: c.width,
		}));
		expect(spreadResize(remembered, 2, 250)).toEqual([200, 200, 200]);
	});
});
