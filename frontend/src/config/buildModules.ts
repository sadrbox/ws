/**
 * МОДУЛИ ПОСТАВКИ: что вообще попадает в сборку установки (Б5 плана
 * PLAN_DEPLOY_AND_MODULES_2026-09-24.md).
 *
 * ЧЕМ ЭТО ОТЛИЧАЕТСЯ ОТ ТОГГЛОВ МОДУЛЕЙ. Тоггл (E11) выключает модуль ОРГАНИЗАЦИИ на работающей
 * установке: код на месте, просто разделы скрыты и запись запрещена. Здесь — уровень выше:
 * модуля нет в сборке вовсе. Нет пункта меню, нет чанка, нечего загрузить и нечего найти в
 * исходниках — ровно то, что владелец просил словами «в сборку входить не должны».
 *
 * КАК ЭТО РАБОТАЕТ. Vite подставляет значение `import.meta.env.*` литералом на этапе сборки,
 * поэтому константа ниже становится `true` или `false` ещё до минификации. Ветки с `false`
 * выбрасываются вместе с динамическими `import()` внутри них — а раз на модуль никто не
 * ссылается, его чанк не создаётся.
 *
 * ОТСЮДА ПРАВИЛО: обращаться к модулю можно ТОЛЬКО через эти константы и только тернарником или
 * `if`. Любая косвенность (переменная, вычисленное имя, таблица) лишит сборщик возможности
 * доказать, что ветка мертва, — и чанк вернётся в сборку молча.
 */

/**
 * Управление 1С: кластеры, агенты, расширение БухПроф-AI.
 *
 * Модуль КОНСАЛТИНГОВОЙ КОМПАНИИ: серверами 1С клиентов управляет она у себя, а на установке
 * клиента этого раздела нет. Включён по умолчанию — наша установка собирается как есть;
 * выключается `VITE_MODULE_ONEC=0` при сборке клиентской поставки.
 */
export const MODULE_ONEC = import.meta.env.VITE_MODULE_ONEC !== "0";

/**
 * Сервер лицензий ЭСФ (К6): выдаёт лицензии ЦЕНТРАЛЬНАЯ установка БухПроф, клиентские к ней
 * обращаются. В публичной сборке реестра лицензий быть не должно.
 */
export const MODULE_ESF_LICENSING = import.meta.env.VITE_MODULE_ESF_LICENSING !== "0";

/** Для отладки и для экрана «о системе»: что вошло в эту сборку. */
export const BUILD_MODULES = {
	onec: MODULE_ONEC,
	esfLicensing: MODULE_ESF_LICENSING,
} as const;
