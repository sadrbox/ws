// Позиции реализации (Sale) — через общую фабрику строк документа.
//
// Раньше здесь жила собственная копия фабрики (расчёт налогов строки, пакетная запись,
// пересчёт суммы), и она отстала от оригинала (аудит 26.09):
//   • строки меняли проведённую реализацию закрытого периода — без assertPeriodOpen (У1);
//   • контроля остатка при правке строк проведённой реализации не было вовсе (У3);
//   • пересбор регистра и проводок шёл отдельно от записи строк и глушил ошибки (У2).
// Фабрика делает всё это одной транзакцией, а расчёт строки у неё тот же (НДС «в т. ч.»
// или «сверху» по настройкам организации на дату документа, акциз, скидка, taxes).
// Партия (batchUuid) и sourceRowId (идемпотентный refill по основанию) — как и были.
import { createDocumentItemsRouter } from "./_documentItemsFactory.js";

export default createDocumentItemsRouter({
	MODEL: "saleItem",
	ROUTE: "saleitems",
	PARENT_MODEL: "sale",
	PARENT_FIELD: "saleUuid",
	hasTaxes: true,
	hasSourceRowId: true,
	extraStringFields: ["batchUuid"], // партия (T6.1): выбор по FEFO на строке реализации
});
