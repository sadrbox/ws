#!/bin/sh
# ─────────────────────────────────────────────────────────────────────────────
# CI-проверка дрейфа: сравнивает фактическую схему БД с schema.prisma.
# Падает (exit 1), если есть расхождения, КРОМЕ осознанных — они перечислены ниже.
#
# ЧТО СЧИТАЕТСЯ ОЖИДАЕМЫМ И ПОЧЕМУ (аудит 22.09, до него проверка была красной всегда,
# и настоящий дрейф в её выводе утонул бы):
#
#   1. ИНДЕКСЫ, КОТОРЫХ PRISMA НЕ УМЕЕТ. Частичные (WHERE) и trgm-индексы в schema.prisma
#      не выразить, они живут в миграциях. Prisma видит их как лишние и предлагает снести —
#      делать этого НЕЛЬЗЯ: на них держатся поиск по классификаторам и уникальность
#      активных штрихкодов. Каждый такой индекс назван поимённо: новый «лишний» индекс,
#      которого нет в списке, по-прежнему уронит проверку.
#
#   2. ИМЕНА ОГРАНИЧЕНИЙ ПОСЛЕ ПЕРЕИМЕНОВАНИЯ ТАБЛИЦ. `user_settings` → `access_rights` и
#      `user_access_rights` → `access_permissions` переименованы давно; в базе остались
#      прежние имена ключей и индексов. Это косметика имён: структура и данные совпадают,
#      а переименовывать ограничения на живой базе ради красоты вывода — работа с риском
#      без выгоды. Отбираются только строки RENAME.
#
# Запуск: sh scripts/check-schema-drift.sh   (или npm run check:drift)
# ─────────────────────────────────────────────────────────────────────────────
set -e
cd "$(dirname "$0")/.."

DIFF=$(npx prisma migrate diff \
  --from-config-datasource prisma.config.js \
  --to-schema prisma/schema.prisma \
  --script 2>/dev/null)

# Индексы, которые Prisma не выражает: их «снос» в выводе — ожидаемый шум, а не дрейф.
EXPECTED_INDEXES='chart_of_accounts_global_code_key|classifiers_code_trgm|classifiers_name_trgm|products_barcode_active_uq|product_barcodes_barcode_active_uq'

# Убираем комментарии, пустые строки, ожидаемые индексы и переименования ограничений.
# `|| true` — grep без совпадений возвращает 1, что под `set -e` уронило бы скрипт.
REST=$(printf '%s\n' "$DIFF" \
  | grep -vE '^[[:space:]]*(--.*)?$' \
  | grep -vE "DROP INDEX \"($EXPECTED_INDEXES)\"" \
  | grep -vE 'RENAME (CONSTRAINT|TO) ' || true)

if [ -n "$REST" ]; then
  echo "❌ Непредвиденный дрейф схемы БД ↔ schema.prisma:"
  printf '%s\n' "$DIFF"
  exit 1
fi

echo "✅ Схема БД соответствует schema.prisma (ожидаемое: индексы, которых Prisma не выражает, и имена ограничений после переименования таблиц)."
