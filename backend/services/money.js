// ─────────────────────────────────────────────────────────────────────────────
// Округление денег и количеств — одно на весь учёт (У9 аудита 26.09).
//
// `Math.round(x * 100) / 100` ошибается на «половинках», которые в двоичной записи
// чуть меньше себя: 1.005 хранится как 1.00499999999999989…, и 1.005 × 100 даёт
// 100.49999999999999 → 100 → 1.00 вместо 1.01 (так же 2.675 → 2.67). На строке это
// копейка, на сумме документа и в сверке с ЭСФ — расхождение, которое не найти глазами.
//
// Поправка — относительная, в несколько ULP: достаточна, чтобы вернуть «половинку»,
// потерянную при умножении, и слишком мала, чтобы сдвинуть честное 100.4999.
// Округление симметрично относительно нуля (−1.005 → −1.01), −0 не возвращается.
// ─────────────────────────────────────────────────────────────────────────────

const NUDGE = 1 + 4 * Number.EPSILON;

/** Округлить до `digits` знаков после запятой (по умолчанию 2 — деньги). Мусор → 0. */
export function roundTo(n, digits = 2) {
	const x = Number(n);
	if (!Number.isFinite(x) || x === 0) return 0;
	const p = 10 ** digits;
	const r = Math.round(Math.abs(x) * p * NUDGE);
	return r === 0 ? 0 : (Math.sign(x) * r) / p;
}

/** Деньги: 2 знака. */
export const r2 = (n) => roundTo(n, 2);
/** Количество: 4 знака (как Decimal(18,4) в строках документов). */
export const r4 = (n) => roundTo(n, 4);

export default { roundTo, r2, r4 };
