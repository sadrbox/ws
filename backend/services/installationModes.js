//
// ПОЧЕМУ ОТДЕЛЬНО ОТ `installation.js`. Там — чтение и запись настроек, то есть Prisma; здесь —
// решения, которые можно проверить тестом без поднятой БД и переиспользовать где угодно
// (установщик, мастер первого запуска, панель). Смешанный модуль не проверить ни быстро, ни
// в гейте `verify` — а именно эти правила и нужно уберечь от случайной правки.

/**
 * Режимы установки.
 *   service  — консалтинг: фирма ведёт учёт организаций-клиентов;
 *   isolated — общий сервер: много организаций, чужих друг другу;
 *   group    — одна группа пользователей на одну или несколько организаций.
 */
export const INSTALL_MODES = ["service", "isolated", "group"];

/**
 * УМОЛЧАНИЕ — `group`, и это выбрано намеренно: оно описывает существующую установку (одна
 * компания, несколько своих юрлиц, общий круг пользователей). Режим у неё никто не задавал, и
 * подстановка «как есть» не меняет поведение ни в одном правиле.
 */
export const DEFAULT_MODE = "group";

/** Неизвестное значение — не ошибка, а «не настроено»: падать на старте из-за опечатки нельзя. */
export function normalizeMode(raw) {
	const v = String(raw ?? "").trim().toLowerCase();
	return INSTALL_MODES.includes(v) ? v : DEFAULT_MODE;
}

/**
 * Открыта ли САМОСТОЯТЕЛЬНАЯ регистрация организации с экрана входа.
 *
 * Правило режима: открыта только у `isolated` — там арендаторы приходят сами. В `service`
 * клиентов заводит фирма, в `group` — администратор группы, и открытая форма означала бы, что
 * посторонний заводит организацию на чужом сервере.
 *
 * ЯВНОЕ ЗНАЧЕНИЕ ГЛАВНЕЕ РЕЖИМА: установка может быть `group`, но временно открыть регистрацию
 * на время переезда — это настройка, а не исключение из правила.
 *
 * @returns {boolean|null} null — сказать нечего (режим не выбран, явного значения нет). Тогда
 *          вызывающий оставляет прежнее поведение: закрывать форму на работающей установке
 *          из-за того, что её никто не настраивал, — худшее, что может сделать эта правка.
 */
export function selfRegistrationAllowed({ mode, override } = {}) {
	if (override === true || override === false) return override;
	if (override === "true") return true;
	if (override === "false") return false;
	if (!mode) return null;
	return normalizeMode(mode) === "isolated";
}

export default { INSTALL_MODES, DEFAULT_MODE, normalizeMode, selfRegistrationAllowed };
