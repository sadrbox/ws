-- `bases.name` — описание базы из среза кластера: каждый heartbeat и «Обновить» переписывают его тем, что сообщил
-- агент, а по нему же сервис узнаёт базу в ответе о публикациях (агент называет базу то ключом, то именем).
-- Править его значило бы и потерять правку при следующем срезе, и сломать это сопоставление. Поэтому имя панели
-- живёт отдельно: срез его не трогает, NULL — показывать имя из кластера.
