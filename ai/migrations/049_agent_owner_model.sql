-- Модель агента без владельца (docs/TASK_SERVICE_AGENT_OWNER_MODEL_2026-09-28.md, Р1, Р2, В1, В4).
--
-- У агента нет организации: кого он обслуживает, говорят его базы. У команды организация — чьи данные затронуты,
-- а у команды кластера и о самой службе её нет вовсе.
--
-- ЭТОТ ШАГ СОВМЕСТИМЫЙ. Колонки не удаляются — только снимается NOT NULL: код с 28.09 их не пишет (новый агент
-- заводится без организации), а откат на прежнюю сборку встретит ту же схему. Удаление колонок и таблицы активации
-- БИН — отдельной миграцией после выкладки: migrations/after-deploy/ (её переносят сюда, когда выкладка проверена).
ALTER TABLE agents ALTER COLUMN organization_uuid DROP NOT NULL;
ALTER TABLE commands ALTER COLUMN organization_uuid DROP NOT NULL;

-- Пустая строка вместо организации (агент кластера, служебные и кластерные команды) — это «никакой», то есть NULL:
-- видимость результата решается по организации команды (В4), и '' не должен выглядеть организацией.
UPDATE commands SET organization_uuid = NULL WHERE organization_uuid = '';
