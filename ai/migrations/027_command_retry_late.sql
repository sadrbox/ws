-- Повтор «база занята» с паузой и поздние результаты (аудит 15.09, С19, С21).
--
-- available_at — раньше этого времени команду не выдавать. Повтор IB_BUSY ставился сразу, а
--                проверка сеансов у агента отвечает за секунды: три попытки сгорали мгновенно,
--                и повтор ничего не давал. NULL — выдавать как обычно.
-- late         — результат пришёл ПОСЛЕ истечения срока команды. Раньше принимался молча: в
--                журнале и отчёте задания команда из «Не выполнено» тихо становилась «Выполнено».
ALTER TABLE commands
	ADD COLUMN available_at timestamptz,
	ADD COLUMN late boolean NOT NULL DEFAULT false;
