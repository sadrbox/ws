-- Очередь команд: место базы, сроки, повторы (аудит 14.09, С1–С3, С10).
--
-- in_base      — команда идёт ВНУТРЬ базы (ib.admin) и занимает место базы и агента. Раньше это
--                определялось наличием base_key, и кластерные команды с базой (снятие сеанса,
--                блокировка входа, удаление регистрации) ждали загрузку той же базы (С1).
--                NULL — старые команды: как прежде, по base_key.
-- ttl_seconds  — срок ВЫПОЛНЕНИЯ, отсчитывается от выдачи агенту. Раньше срок шёл от постановки,
--                и базы группового задания истекали, не дождавшись очереди (С2). NULL — старые.
-- attempt      — номер попытки (повтор при IB_BUSY, С10).
-- retried_by   — команда-повтор; повторённая в отчёте задания не показывается.
ALTER TABLE commands
	ADD COLUMN in_base boolean,
	ADD COLUMN ttl_seconds integer,
	ADD COLUMN attempt integer NOT NULL DEFAULT 1,
	ADD COLUMN retried_by text;
