-- Идентификатор информационной базы в кластере (E15).
--
-- ЗАЧЕМ. Сеансы кластера приходят одним списком, и каждая строка ссылается на базу
-- ПО UUID (поле infobase), а не по имени. Без этого uuid отобрать сеансы конкретной базы
-- можно было только отдельной командой агенту с baseKey — а она у него ломается там, где
-- сеансов нет, и пользователь видел «база не найдена в кластере» вместо пустого списка.
-- С сохранённым uuid отбор делается на месте, из уже полученного среза, и лишняя команда
-- к 1С не нужна вовсе.
ALTER TABLE bases ADD COLUMN infobase_id text;
CREATE INDEX bases_infobase_id_idx ON bases (infobase_id) WHERE infobase_id IS NOT NULL;
