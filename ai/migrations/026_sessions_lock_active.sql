-- Действует ли блокировка начала сеансов СЕЙЧАС (агент 2026-09-14 23:16, `lock.active`).
--
-- «Включена» и «действует» — разное: `rac infobase update` не стирает окно прошлой блокировки, и
-- включённая без окна блокировка с прошедшим окном вход не закрывает. Панель показывала «Вход
-- закрыт», а пользователи входили. `active` агент считает у себя (включена И сейчас внутри окна) —
-- по местному времени сервера 1С, которого сервис не знает, поэтому хранится как прочитано.
-- NULL — не сообщал (старая сборка, незнакомый вид дат, запись по команде без эха).
ALTER TABLE bases ADD COLUMN sessions_denied_active boolean;
