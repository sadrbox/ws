-- Откуда известно «Показывать в списке выбора» у пользователя ИБ (E15, задача A2 от 13.09).
--
-- ЗАЧЕМ. Колонка show_in_list (миграция 019) хранит значение из двух разных источников:
-- прочитанное у 1С (список пользователей или эхо команды) и запомненное по успешной записи
-- панели. Карточка подписывала показанное по одному признаку «значение есть» — и как только
-- агент начнёт отдавать признак, прочитанное из базы было бы подписано «прочитать неоткуда».
-- Значение, которое помнит панель, — это то, что МЫ записали; значение из базы — то, что
-- там сейчас. Показывать их одинаково нельзя: второе видит правку из конфигуратора, первое — нет.
--
-- 'base'  — прочитано у 1С; 'panel' — запомнено по успешной записи панели; NULL — неизвестно.
ALTER TABLE base_users ADD COLUMN show_in_list_source text
	CHECK (show_in_list_source IN ('base', 'panel'));

-- Всё, что было известно до этой миграции, записала панель: агент признак не отдавал ни разу.
UPDATE base_users SET show_in_list_source = 'panel' WHERE show_in_list IS NOT NULL;

COMMENT ON COLUMN base_users.show_in_list_source IS
	'Откуда show_in_list: base — прочитано у 1С, panel — по успешной записи панели, NULL — неизвестно.';
