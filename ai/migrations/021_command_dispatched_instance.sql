-- Какой ПРОЦЕСС агента забрал команду (E15/A5).
--
-- ЗАЧЕМ. Команда, выданная агенту, живёт в состоянии `dispatched` до результата или до
-- истечения срока — 15 минут. Если процесс агента в это время перезапустили (обновление
-- службы), результата не будет никогда: новый процесс о забранной команде не знает, в spool
-- она не попадает (там только готовые результаты). А при `AGENT_IB_PARALLEL = 1` одна такая
-- «мёртвая» команда занимает единственное место внутрибазовых операций, и следующие
-- пятнадцать минут панель показывает «Выполняется» там, где не выполняется ничего.
--
-- Живой случай 12.09 23:14: служба агента обновлена, забранная ею IB_LIST_USERS по базе
-- `abdali` осталась без ответа, и все внутрибазовые команды встали до 23:26.
--
-- Имя экземпляра агент присылает сам (заголовок X-Agent-Instance / поле instanceId): оно
-- стабильно в пределах жизни процесса и разное у разных процессов. Записав его рядом с
-- командой, сервис при регистрации НОВОГО процесса видит, какие команды забирал прежний, и
-- закрывает их сразу, а не через четверть часа.
--
-- NULL — «не знаем, кто забрал»: так помечены команды, выданные до этой миграции, и
-- сборками агента без заголовка. Такие не трогаем никогда — они закрываются по сроку, как
-- раньше: догадка здесь хуже ожидания.
ALTER TABLE commands ADD COLUMN dispatched_instance text;

COMMENT ON COLUMN commands.dispatched_instance IS
	'Экземпляр (процесс) агента, забравший команду. NULL — неизвестно: закрывать только по сроку.';
