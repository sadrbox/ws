-- Публичный адрес сервера 1С — для ссылок на опубликованные базы (E15).
--
-- ЗАЧЕМ. Агент собирает адрес публикации из привязки сайта IIS и отдаёт то, что там
-- написано: при привязке без имени узла (`http/*:80:`) это `http://localhost/<база>`.
-- Ответ честный — с самого сервера ссылка рабочая, — но снаружи по ней не попасть.
--
-- Подменять адрес В ДАННЫХ нельзя: это то, что сообщил агент, и портить его догадкой
-- значит лишиться возможности заметить настоящую ошибку в привязке. Поэтому здесь хранится
-- ОТДЕЛЬНОЕ знание — под каким именем этот сервер виден снаружи, — а ссылка для показа
-- собирается из него и пути, который прислал агент.
--
-- Свойство СЕРВЕРА, а не установки: серверов может быть несколько, и у каждого своё имя.
ALTER TABLE servers ADD COLUMN IF NOT EXISTS public_host text;
