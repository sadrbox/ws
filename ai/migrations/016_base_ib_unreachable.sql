-- База числится в кластере, но войти в неё нельзя (E15).
--
-- ЧТО СЛУЧИЛОСЬ. Состояние базы держалось в одном поле `status`, и его писали ДВА источника,
-- которые знают разное:
--   • срез кластера (`rac list_infobases`) отвечает на вопрос «ЗАРЕГИСТРИРОВАНА ли база» —
--     и для базы, снесённой на СУБД, но оставшейся записью в кластере, честно говорит ONLINE:
--     запись-то есть;
--   • вход в базу (COM/ibcmd) отвечает на вопрос «МОЖНО ли с ней работать» — и для той же
--     базы возвращает INFOBASE_NOT_FOUND.
--
-- Сервис помечал такую базу `status = MISSING`, но ближайший срез кластера возвращал ей
-- ONLINE: источник, который не умеет входить в базу, затирал знание источника, который
-- входил и не нашёл. Дальше по кругу: база выглядит рабочей, человек жмёт «Обновить», ждёт,
-- получает «база не найдена на сервере», и через минуту всё повторяется.
--
-- Признак живёт ОТДЕЛЬНО от `status`, потому что это отдельный факт. Ставится при
-- INFOBASE_NOT_FOUND, снимается первой же удачной командой внутрь базы — то есть тем самым
-- источником, который его и поставил. Срез кластера его не трогает вовсе.
ALTER TABLE bases ADD COLUMN IF NOT EXISTS ib_unreachable_at timestamptz;

-- Базы, уже помеченные MISSING по отказу входа, переносим в новый признак: их `status`
-- всё равно вернётся к ответу кластера при ближайшем срезе, и знание потерялось бы.
UPDATE bases SET ib_unreachable_at = now() WHERE status = 'MISSING';
