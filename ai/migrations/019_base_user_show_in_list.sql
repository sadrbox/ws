-- «Показывать в списке выбора» у пользователя ИБ (E15).
--
-- ЗАЧЕМ. Панель умеет ЗАПИСЫВАТЬ этот признак (IB_CREATE_USER/IB_UPDATE_USER принимают
-- showInList), но прочитать его неоткуда: IB_LIST_USERS по контракту возвращает только
-- {name, fullName, disabled, roles}. Форма показывала выдуманное «включено», а при любом
-- «Применить» это выдуманное значение уходило в 1С и затирало настоящее.
--
-- Колонка трёхзначная намеренно: NULL — «агент не сообщил», и это НЕ «выключено». Пока
-- сборка агента не отдаёт признак, карточка так и говорит: значение не читается, выберите,
-- что записать. Появится в ответе — значение станет известным без единой правки здесь.
ALTER TABLE base_users ADD COLUMN show_in_list boolean;

COMMENT ON COLUMN base_users.show_in_list IS
	'Показывать пользователя в списке выбора при входе. NULL — агент не сообщил (не «нет»).';
