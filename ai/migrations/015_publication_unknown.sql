-- Состояние публикации: «не проверялось» вместо выдуманного «нет» (E15).
--
-- ЧТО СЛУЧИЛОСЬ. Признак публикации принимался из среза БАЗ, который приходит от rac. Про
-- веб-публикации rac не знает ничего, и агент клал туда «не опубликована» для всех — в том
-- числе для базы, которую панель опубликовала своей же командой минутой раньше. Так сто
-- десять баз оказались помечены «не опубликована», и панель уверенно показывала это как факт.
--
-- Отличить теперь правду от затирания нельзя ни по одной записи: снимок один на всех. Поэтому
-- признак сбрасывается в NULL — «не проверялось». Это честное состояние: оно есть в модели
-- именно для таких случаев, и панель для него показывает «не проверялась», а не «нет».
--
-- Заполнится он при первом же удачном срезе публикаций («Обновить публикации» в списке баз)
-- или после нашей команды публикации/снятия.
UPDATE bases
   SET published = NULL, publish_url = NULL, publish_seen_at = NULL
 WHERE published = false;
