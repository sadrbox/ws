-- ПОЧЕМУ в базу не войти: «её нет в СУБД» и «не удалось войти» — разные беды (E15).
--
-- Признак «числится в кластере, но войти нельзя» появился в 016 и отвечал только «да/нет».
-- Живой случай показал, что этого мало: у базы `aibek` кластер отвечает ONLINE, а ibcmd —
-- «База данных отсутствует в сервере баз данных. Не найдена база данных 'aibek' в
-- SQL-сервере 'localhost'». Это не временный отказ и не вопрос прав: самой базы нет, и
-- никакая команда внутрь неё никогда не выполнится. Лечится это не повтором, а решением
-- администратора — восстановить из копии либо убрать регистрацию из кластера.
--
-- Причину храним КОДОМ, а не текстом агента: текст меняется от версии к версии и от
-- утилиты к утилите, а решение по нему принимает панель (что показать и что предложить).
--   NO_DB        — базы нет в СУБД (запись в кластере осталась);
--   NO_INFOBASE  — базы нет и в самом кластере (регистрацию уже убрали);
--   NO_ACCESS    — база есть, но войти не дают (учётные данные, права);
--   UNKNOWN      — войти не удалось, причину классифицировать не смогли.
ALTER TABLE bases ADD COLUMN ib_unreachable_reason text;

COMMENT ON COLUMN bases.ib_unreachable_reason IS
	'Почему в базу не войти: NO_DB | NO_INFOBASE | NO_ACCESS | UNKNOWN. NULL — войти можно.';
