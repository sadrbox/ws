-- Приоритет команды: интерактивное действие вперёд массового (T22).
--
-- ЗАЧЕМ. Групповое чтение полусотни баз занимает очередь целиком, и одиночное «Обновить»,
-- нажатое человеком следом, ждёт, пока разгребут пачку. Для того, кто сидит за экраном, это
-- выглядит как «панель зависла», хотя она честно стоит в общей очереди.
--
-- Меньше значение — раньше выдача. 0 — то, что человек запросил сейчас и ждёт на экране;
-- 10 — пакетные операции по многим базам: их запускают и уходят.
ALTER TABLE commands ADD COLUMN priority smallint NOT NULL DEFAULT 0;
CREATE INDEX commands_dispatch_idx ON commands (agent_id, state, priority, created_at);
