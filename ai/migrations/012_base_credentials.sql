-- Своя учётная запись администратора ДЛЯ ОТДЕЛЬНОЙ БАЗЫ (E15/A3).
--
-- ЗАЧЕМ. Агент на сервере 1С знает ОДНОГО администратора баз (у нас — support). Он подходит
-- к большинству баз, но не ко всем: часть клиентских баз заведена до нас, и в них такого
-- пользователя просто нет либо у него другой пароль. Раньше это выглядело как «команда
-- отказала, администратор кластера не аутентифицирован» — и лечилось только правкой
-- настроек агента на сервере, то есть выездом к серверу ради одной базы.
--
-- Теперь для базы можно задать СВОЮ пару «пользователь + пароль». Агент по-прежнему сначала
-- пробует своего администратора: смена его учётных данных не требуется, а исключение
-- заводится ровно там, где оно нужно.
--
-- ПАРОЛЬ ХРАНИТСЯ ЗАШИФРОВАННЫМ (aes-256-gcm, ключ выводится из секрета сервиса). Это
-- защищает выгрузку базы и резервные копии — но не сервис, у которого ключ есть по долгу
-- службы. Обратимое шифрование здесь неизбежно: пароль нужно ОТДАТЬ агенту, а не сверить.
--
-- Отдельная таблица, а не колонки в bases: строки bases уходят в панель целиком, и колонке
-- с шифртекстом там не место — рано или поздно она попала бы в ответ.
CREATE TABLE base_credentials (
    base_id     uuid PRIMARY KEY REFERENCES bases(id) ON DELETE CASCADE,
    -- Имя пользователя базы. Не секрет: показывается в карточке базы.
    user_name   text NOT NULL,
    -- Шифртекст пароля в виде v1:<iv>:<tag>:<data> (base64). Пустая строка = пароль не задан.
    secret      text NOT NULL DEFAULT '',
    updated_at  timestamptz NOT NULL DEFAULT now(),
    -- Кто задал — для журнала: пароль к чужой базе это не рядовая настройка.
    updated_by  text
);
