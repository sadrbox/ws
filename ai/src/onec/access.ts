/**
 * ДВА ПРАВА ВМЕСТО ОДНОГО (F5): что в панели 1С считается разрушающим.
 *
 * ЗАЧЕМ. Право было одно на всё: посмотреть сеансы базы и удалить её регистрацию стоили
 * одинаково. А это разные вещи и разные люди: состояние смотрят все, кто обслуживает
 * клиентов, а снимать публикацию, править пользователей ИБ и загружать базу поверх
 * существующей — единицы. Уровень `readonly` у права OneCAdmin существовал и раньше, но
 * ничего не значил: сервис его не различал.
 *
 * ЧТЕНИЕ ОСТАЁТСЯ ЧТЕНИЕМ, даже когда за ним стоит команда агенту: перечитать срез баз и
 * публикаций, спросить у базы её пользователей или расширения, проверить базу (`ibcmd
 * check`) — вопросы к 1С, они в ней ничего не меняют.
 *
 * СПИСКОМ, А НЕ ПО МЕТОДУ. Соблазн «GET — чтение, остальное — запись» здесь неверен:
 * половина чтений сделана POST'ом, потому что несёт тело (перечитать срез, проверить базу,
 * прочитать пользователей выбранных баз). Поэтому разрушающее перечислено прямо — новый
 * маршрут попадает в список сознательно, а не по форме запроса.
 *
 * Отдельный модуль — чтобы этот список можно было прочитать и проверить тестом, не поднимая
 * ни express, ни базы: он описывает ПОЛИТИКУ доступа, а ошибка в нём не видна на глаз.
 */

/** Пути внутри роутера `/v1/onec`, меняющие 1С, агентов или их доступ. */
const DESTRUCTIVE: RegExp[] = [
	// Пакетные изменения: пользователи ИБ, расширения, публикация, выгрузка базы.
	/^\/batch$/,
	// Повтор задания ставит те же изменяющие команды заново; отмена управляет очередью.
	/^\/batches\/[^/]+\/(cancel|retry)$/,
	/^\/commands\/cancel$/,
	// Вмешательство в работу людей в базе.
	/^\/sessions\/[^/]+\/terminate$/,
	/^\/connections\/[^/]+\/disconnect$/,
	// Настройки сервера: адрес публикации, параметры rac.
	/^\/servers\/[^/]+$/,
	// Агенты: регистрация, переименование, отключение, владелец, освобождение экземпляра и
	// ротация токена — доступ к серверу 1С как таковой.
	/^\/agents$/,
	/^\/agents\/[^/]+$/,
	/^\/agents\/[^/]+\/(owner|release-instance|rotate-token)$/,
	/^\/agent-processes\/[^/]+\/kill$/,
	// Служебный администратор базы: пара «имя + пароль», которой агент входит в базу.
	/^\/bases\/[^/]+\/credentials$/,
	// Сама база: скрыть, заблокировать сеансы, загрузить поверх, обновить конфигурацию,
	// удалить регистрацию.
	/^\/bases\/[^/]+\/(hidden|lock|restore|apply-update|drop-registration)$/,
	// Расписание обслуживания (F2): смотреть его может всякий, кому открыта панель, а
	// заводить и запускать — нет. Ночная выгрузка занимает сервер часами.
	/^\/schedules$/,
	/^\/schedules\/[^/]+$/,
	/^\/schedules\/[^/]+\/run$/,
];

/**
 * Требует ли запрос полного доступа.
 *
 * `GET` не бывает разрушающим: часть путей читают и меняют одно и то же (GET
 * `/bases/:key/credentials` отдаёт признак «задан», PUT того же пути — записывает пароль).
 */
export function isDestructive(method: string, path: string): boolean {
	if (method.toUpperCase() === "GET") return false;
	return DESTRUCTIVE.some((re) => re.test(path));
}
