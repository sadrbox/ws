/** Типы заданий, которые только читают 1С: такое задание — не разрушающее. */
const READ_BATCH_TYPES = new Set(["IB_INFO"]);

/** Пути внутри роутера `/v1/onec`, меняющие 1С, агентов или их доступ. */
const DESTRUCTIVE: RegExp[] = [
	// Пакетные изменения: пользователи ИБ, расширения, публикация, выгрузка базы.
	/^\/batch$/,
	// Повтор задания ставит те же изменяющие команды заново; отмена управляет очередью.
	/^\/batches\/[^/]+\/(cancel|retry)$/,
	/^\/commands\/cancel$/,
	// Прерывание начатой команды останавливает работу агента на сервере 1С (S4).
	/^\/commands\/[^/]+\/abort$/,
	// Вмешательство в работу людей в базе.
	/^\/sessions\/[^/]+\/terminate$/,
	/^\/connections\/[^/]+\/disconnect$/,
	// Настройки сервера: адрес публикации, параметры rac.
	/^\/servers\/[^/]+$/,
	// Агенты: регистрация, переименование, отключение, владелец, освобождение экземпляра и
	// ротация токена — доступ к серверу 1С как таковой.
	/^\/agents$/,
	/^\/agents\/[^/]+$/,
	/^\/agents\/[^/]+\/(owner|release-instance|rotate-token|limits|active-bins|config|restart|update)$/,
	/^\/agent-processes\/[^/]+\/kill$/,
	// Служебный администратор базы: пара «имя + пароль», которой агент входит в базу.
	/^\/bases\/[^/]+\/credentials$/,
	// Сама база: скрыть, заблокировать сеансы, загрузить поверх, обновить конфигурацию,
	// удалить регистрацию; самопроверка агента создаёт и удаляет временного пользователя (R4).
	/^\/bases\/[^/]+\/(hidden|lock|restore|apply-update|drop-registration|selftest)$/,
	// Расписание обслуживания (F2): смотреть его может всякий, кому открыта панель, а
	// заводить и запускать — нет. Ночная выгрузка занимает сервер часами.
	/^\/schedules$/,
	/^\/schedules\/[^/]+$/,
	/^\/schedules\/[^/]+\/run$/,
	// Заявки на подключение баз и токены баз (СВ4): одобрение выдаёт базе доступ, отзыв его отнимает.
	/^\/registrations\/[^/]+\/(approve|reject)$/,
	/^\/base-tokens\/[^/]+\/revoke$/,
	// Активация БИНов (СВ4, часть 2): одобрение меняет, какие организации обслуживает агент.
	/^\/activation-requests\/[^/]+\/[^/]+\/(approve|reject)$/,
	/^\/active-bins\/fix-all$/,
	// Подключение агента по коду (СВ5): одобрение выдаёт службе токен доступа.
	/^\/enrollments\/[^/]+\/(approve|reject)$/,
];

/**
 * Требует ли запрос полного доступа.
 *
 * `GET` не бывает разрушающим: часть путей читают и меняют одно и то же (GET
 * `/bases/:key/credentials` отдаёт признак «задан», PUT того же пути — записывает пароль).
 */
export function isDestructive(method: string, path: string, body?: unknown): boolean {
	if (method.toUpperCase() === "GET") return false;
	// Убрать из реестра базу, которой нет в кластере (С45). Только DELETE: POST того же вида — чтения
	// (`/bases/refresh`, `/bases/check`), и регулярка без метода объявила бы их разрушающими.
	if (method.toUpperCase() === "DELETE" && /^\/bases\/[^/]+$/.test(path)) return true;
	// Задание из одних чтений — чтение (17.09): «Обновить сведения» по отмеченным базам в карточке доступно и
	// просмотру, в списке — тоже. Изменяющие типы заданий по-прежнему требуют полного доступа.
	if (path === "/batch" && READ_BATCH_TYPES.has(String((body as { type?: unknown } | null | undefined)?.type ?? "").toUpperCase())) {
		return false;
	}
	// Проверка базы — чтение, пока не просят исправлять (С4): «Исправлять» меняет данные базы.
	if (/^\/bases\/[^/]+\/check$/.test(path)) {
		return (body as { repair?: unknown } | null | undefined)?.repair === true;
	}
	return DESTRUCTIVE.some((re) => re.test(path));
}
