/**
 * СПРАВОЧНИК «Пользователи» ПОСЛЕ КОМАНДЫ — строкой отчёта задания (П31, агент 2026-09-17 19:16).
 *
 * Команда меняет пользователя ИНФОРМАЦИОННОЙ БАЗЫ, а работа человека в программе зависит ещё и от элемента
 * справочника «Пользователи»: без него типовая (БСП) в программу не пустит, а если их два — не пустит тем более.
 * Агент теперь считает эти элементы и кладёт в ответ `catalog: {found, created, items}`.
 *
 * ЧТО ЗНАЧАТ ЧИСЛА:
 *   0 — у НОВОГО пользователя это норма: элемент создаст сама типовая при первом входе. Пишем об этом прямо,
 *       иначе «элементов: 0» читается как поломка;
 *   1 — обычный случай;
 *   >1 — дубль: вход в программу невозможен, чинится «Поиском и удалением дублей» (см. IB_USER_DUPLICATE).
 *       До записи такой отказ ловит сам агент; сюда число попадает, если дубль завёлся между проверкой и чтением;
 *   null + error — прочитать справочник не удалось: команда при этом выполнена, и молчать об этом нельзя.
 *
 * `created` агент ставит ВСЕГДА `false` — элементов справочника он не создаёт и не правит. Поэтому «создан элемент
 * справочника» здесь не пишется никогда: это была бы неправда о том, кто изменил данные.
 */

const isObj = (v: unknown): v is Record<string, unknown> => !!v && typeof v === "object" && !Array.isArray(v);

/** Команды, у которых справочник вообще имеет смысл: они меняют пользователя ИБ. */
const USER_COMMANDS = new Set(["IB_CREATE_USER", "IB_UPDATE_USER", "IB_DELETE_USER"]);

export function catalogOutcome(
	type: string,
	result: unknown,
): { outcome: string; warning: string | null } | null {
	if (!USER_COMMANDS.has(type) || !isObj(result)) return null;
	const c = result.catalog;
	// Поля нет вовсе — конфигурация не на БСП либо агент старее: молчим, а не пишем «0».
	if (!isObj(c)) return null;

	const found = typeof c.found === "number" && Number.isFinite(c.found) ? c.found : null;
	if (found === null) {
		const why = typeof c.error === "string" && c.error.trim() ? `: ${c.error.trim()}` : "";
		return { outcome: "справочник «Пользователи» прочитать не удалось", warning: `справочник «Пользователи» прочитать не удалось${why}` };
	}
	if (found === 0) {
		// У удаления пользователя ИБ ноль — тоже норма и не про первый вход: элемента просто нет.
		return {
			outcome: type === "IB_DELETE_USER"
				? "элементов справочника «Пользователи»: 0"
				: "элементов справочника «Пользователи»: 0 — его создаст программа при первом входе пользователя",
			warning: null,
		};
	}
	if (found === 1) return { outcome: "элемент справочника «Пользователи»: 1", warning: null };
	return {
		outcome: `элементов справочника «Пользователи»: ${found}`,
		warning: `в справочнике «Пользователи» несколько элементов одного пользователя ИБ (${found}) — `
			+ "вход в программу для него невозможен, уберите дубль обработкой «Поиск и удаление дублей»",
	};
}
