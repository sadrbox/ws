/**
 * КТО ДЕРЖИТ БАЗУ — разобранным, а не абзацем (П25).
 *
 * Платформа пишет держателя прозой: «База данных заблокирована: компьютер: SERVER, сеанс: 2, начат: 16.09.2026
 * в 9:54:27, приложение: Фоновое задание». Человеку этого мало: по нему нельзя ни снять сеанс кнопкой, ни понять
 * с одного взгляда, что мешает — конфигуратор коллеги или фоновое задание, которое блокировкой входа не убрать.
 * Разбираем узко: не узнали — возвращаем null, и панель покажет текст как есть.
 */
export type LockedBy = {
	computer: string | null; sessionId: string | null; startedAt: string | null; appId: string | null;
	/** Пользователь сеанса и начало в ISO — есть только у полей агента (с 12:13). */
	user?: string | null; startedAtIso?: string | null;
};

/**
 * ДЕРЖАТЕЛЬ ОТ АГЕНТА — в форму панели (С42). Агент с `2026-09-16 12:13` сам кладёт `details.lockedBy`
 * `{computer, session, application, user?, startedAt (ISO), startedText}`. Разбирать текст поверх — хуже: агент
 * обрезает его до 400 символов, и приложение в хвосте пропадает. Поля переименовываем под панель; разбор текста —
 * только для агентов старше.
 */
export function normalizeLockedBy(v: unknown): LockedBy | null {
	const o = Array.isArray(v) ? v[0] : v;
	if (!o || typeof o !== "object") return null;
	const r = o as Record<string, unknown>;
	const s = (x: unknown): string | null => (typeof x === "string" && x.trim() ? x.trim() : typeof x === "number" ? String(x) : null);
	const out: LockedBy = {
		computer: s(r.computer),
		sessionId: s(r.session ?? r.sessionId),
		appId: s(r.application ?? r.appId),
		startedAt: s(r.startedText) ?? s(r.startedAt),
		user: s(r.user),
		startedAtIso: s(r.startedAt),
	};
	return out.computer || out.sessionId || out.appId ? out : null;
}

const FIELD = (name: string, text: string): string | null => {
	const m = new RegExp(`${name}\\s*:\\s*([^,]+?)\\s*(?:,|$)`, "i").exec(text);
	return m ? m[1].trim() : null;
};

export function parseLockedBy(message: string | null | undefined): LockedBy | null {
	const text = message ?? "";
	if (!/база данных заблокирована|разделен\w* доступ|разделённ\w* доступ/i.test(text)) return null;
	const out: LockedBy = {
		computer: FIELD("компьютер", text),
		sessionId: FIELD("сеанс", text),
		startedAt: FIELD("начат", text),
		appId: FIELD("приложение", text),
	};
	// Ни одного поля — разбирать нечего: пусть панель покажет текст платформы как есть.
	return Object.values(out).some((v) => v) ? out : null;
}

/** Кто ответил: агент кладёт машину и процесс в `details` ошибки. */
export type AgentErrorDetails = { host?: unknown; pid?: unknown; build?: unknown };

/**
 * Строка «ответил агент на такой-то машине».
 *
 * Под одним токеном может работать несколько процессов на разных машинах, и тогда одна и та
 * же команда то проходит, то падает «база не найдена». Без имени машины в тексте ошибки это
 * не разгадать: в отчёте видно только чередование.
 */
export function describeResponder(details: unknown): string | null {
	const d = (details ?? {}) as AgentErrorDetails;
	const host = typeof d.host === "string" ? d.host : null;
	if (!host) return null;
	const pid = typeof d.pid === "number" || typeof d.pid === "string" ? `, pid ${d.pid}` : "";
	const build = typeof d.build === "string" ? `, сборка ${d.build}` : "";
	return `Ответил агент на машине ${host}${pid}${build}.`;
}

