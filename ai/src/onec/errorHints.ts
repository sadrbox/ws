/**
 * ССЫЛКИ НА ДУБЛИ — списком, а не абзацем (С43).
 *
 * Агент отдаёт `details.duplicates: [{ref, catalog, deleted}]`: ref — UUID элемента справочника, catalog —
 * «Пользователи» или «ВнешниеПользователи», deleted — помечен ли на удаление. Помеченный на удаление важен
 * отдельно: он выглядит как «уже убранный», но для типовой он такой же элемент, и вход он блокирует так же.
 */
export function duplicatesText(details: unknown): string {
	const list = (details as { duplicates?: unknown } | null | undefined)?.duplicates;
	if (!Array.isArray(list) || !list.length) return "";
	const lines = list
		.map((v) => (v && typeof v === "object" ? v as Record<string, unknown> : null))
		.filter((v): v is Record<string, unknown> => !!v)
		.map((d) => {
			const catalog = typeof d.catalog === "string" && d.catalog.trim() ? d.catalog.trim() : "Пользователи";
			const ref = typeof d.ref === "string" && d.ref.trim() ? d.ref.trim() : "—";
			return `• ${catalog}: ${ref}${d.deleted === true ? " (помечен на удаление)" : ""}`;
		});
	return lines.length ? `Элементы справочника (${lines.length}):\n${lines.join("\n")}` : "";
}

/**
 * КОД ДЛЯ ЖУРНАЛА 1С (СВ0). Расширение 1.3.0 на 500 INTERNAL_ERROR не раскрывает подробностей наружу, а кладёт
 * в журнал регистрации запись и отдаёт её ключ `details.errorId`: по нему администратор базы находит полный текст.
 */
export function errorIdText(details: unknown): string {
	const id = (details as { errorId?: unknown } | null | undefined)?.errorId;
	return typeof id === "string" && id.trim() ? `Код для поиска в журнале 1С: ${id.trim()}` : "";
}

export function humanizeAgentError(
	e: { code: string; message: string; details?: unknown } | null,
	ctx: AuthContext = {},
): { code: string; message: string; details?: unknown } | null {
	if (!e?.message) return e;
	const parts: string[] = [];
	const authFailed = e.code === "IB_AUTH_FAILED" || IB_AUTH_FAILED.test(e.message);
	if (ctx.baseAuthUser && authFailed) {
		parts.push(ctx.agentSupportsBaseAuth === false
			? `Для базы задана своя учётная запись (имя: «${ctx.baseAuthUser}»), и сервис передал её `
				+ "агенту в payload.auth, но АГЕНТ ЭТОЙ СБОРКИ ЕЁ НЕ ПРИМЕНЯЕТ: он не объявляет "
				+ "способность «ib.auth». Пока агента не обновят, отдельная учётная запись базы "
				+ "не работает — отказ выше получен по администратору из настроек агента."
			: `Для базы задана своя учётная запись (имя: «${ctx.baseAuthUser}»), и сервис передал её `
				+ "агенту. Раз вход всё равно не выполнен — значит, не подошла и она. Сверьте имя "
				+ "ПОСИМВОЛЬНО: 1С отвечает одинаково на неизвестное имя и на неверный пароль, "
				+ "поэтому имя, обрезанное на один знак, выглядит как «просто неверный пароль».");
	}
	// Подсказка по КОДУ — там, где текст агента зависит от утилиты, а смысл один (С13).
	const byCode = e.code === "IB_CONNECTION_LOST" && LIMITS_NOT_SET.test(e.message)
		? CONNECTION_LOST_CRASH_HINT
		: CODE_HINTS[e.code];
	// Отказ по лимиту от самого сервиса уже говорит, что делать (agents/agentBases) — второй совет не нужен.
	const saysRemedy = e.code === "LICENSE_LIMIT" && /увеличьте тариф/i.test(e.message);
	if (byCode && !saysRemedy && !e.message.includes(byCode)) parts.push(byCode);
	const found = HINTS.find((h) => h.match.test(e.message)) ?? (e.code === "IB_AUTH_FAILED" ? AUTH_HINT : undefined);
	// Подсказка приписывается один раз: повторный проход по уже дополненному тексту
	// (список задания читают многократно) не должен наращивать его бесконечно.
	if (found && !e.message.includes(found.hint)) parts.push(found.hint);
	const ref = errorIdText(e.details);
	if (ref && !e.message.includes(ref)) parts.push(ref);
	const dup = duplicatesText(e.details);
	if (dup && !e.message.includes(dup)) parts.push(dup);
	const who = describeResponder(e.details);
	if (who && !e.message.includes(who)) parts.push(who);
	if (!parts.length) return e;
	return { ...e, message: [e.message, ...parts].join("\n\n") };
}
