export function humanizeAgentError(
	e: { code: string; message: string; details?: unknown } | null,
	ctx: AuthContext = {},
): { code: string; message: string; details?: unknown } | null {
	if (!e?.message) return e;
	const parts: string[] = [];
	const authFailed = e.code === "IB_AUTH_FAILED" || IB_AUTH_FAILED.test(e.message);
	if (ctx.baseAuthUser && authFailed) {
		parts.push(ctx.agentSupportsBaseAuth === false
			? `Для базы задана своя учётная запись (имя: «${ctx.baseAuthUser}»), и сервис передал её `
				+ "агенту в payload.auth, но АГЕНТ ЭТОЙ СБОРКИ ЕЁ НЕ ПРИМЕНЯЕТ: он не объявляет "
				+ "способность «ib.auth». Пока агента не обновят, отдельная учётная запись базы "
				+ "не работает — отказ выше получен по администратору из настроек агента."
			: `Для базы задана своя учётная запись (имя: «${ctx.baseAuthUser}»), и сервис передал её `
				+ "агенту. Раз вход всё равно не выполнен — значит, не подошла и она. Сверьте имя "
				+ "ПОСИМВОЛЬНО: 1С отвечает одинаково на неизвестное имя и на неверный пароль, "
				+ "поэтому имя, обрезанное на один знак, выглядит как «просто неверный пароль».");
	}
	// Подсказка по КОДУ — там, где текст агента зависит от утилиты, а смысл один (С13).
	const byCode = e.code === "IB_CONNECTION_LOST" && LIMITS_NOT_SET.test(e.message)
		? CONNECTION_LOST_CRASH_HINT
		: CODE_HINTS[e.code];
	if (byCode && !e.message.includes(byCode)) parts.push(byCode);
	const found = HINTS.find((h) => h.match.test(e.message)) ?? (e.code === "IB_AUTH_FAILED" ? AUTH_HINT : undefined);
	// Подсказка приписывается один раз: повторный проход по уже дополненному тексту
	// (список задания читают многократно) не должен наращивать его бесконечно.
	if (found && !e.message.includes(found.hint)) parts.push(found.hint);
	const who = describeResponder(e.details);
	if (who && !e.message.includes(who)) parts.push(who);
	if (!parts.length) return e;
	return { ...e, message: [e.message, ...parts].join("\n\n") };
}
