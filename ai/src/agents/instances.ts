/**
 * Единственность экземпляра агента: под одним токеном работает ОДИН процесс.
 *
 * ЗАЧЕМ. Два процесса под одним токеном разбирают одну очередь команд. Пока их настройки
 * совпадают, это лишь двойная нагрузка; стоит им разойтись — и одна и та же команда
 * начинает отказывать через раз, а часть команд уходит на машину, где нужных баз нет
 * вовсе. Разбор такого случая стоит часов: с сервера видно только чередование ответов.
 *
 * ЧТО ЭТО НЕ ЕСТЬ. Не аутентификация. Идентификатор экземпляра называет сам агент, и
 * подделать его тривиально. Это защита от ОШИБКИ — запущенной второй копии, забытого
 * экземпляра из среды разработки, скопированного на вторую машину токена. От злого умысла
 * защищает не это, а один токен на машину и его ротация.
 *
 * АРЕНДА, А НЕ ЗАПРЕТ НАВСЕГДА. Владение живёт, пока владелец подаёт признаки жизни. Молчит
 * дольше `offlineAfterSecs` — считается ушедшим, и следующий экземпляр забирает владение
 * сам. Иначе перезапуск службы или переезд на другую машину требовали бы ручного действия
 * в панели, а агент после падения не поднялся бы вовсе.
 */

export type InstanceDecision =
	/** Владельца нет (или прежний ушёл) — этот экземпляр становится владельцем. */
	| { kind: "claim" }
	/** Пришёл владелец — просто отмечаем, что он жив. */
	| { kind: "refresh" }
	/** Пришёл чужой при живом владельце — отказ. */
	| { kind: "reject"; ownerInstanceId: string; ownerSeenSecsAgo: number };

export function decideInstance(input: {
	/** Кто владеет сейчас; null — владельца нет. */
	ownerInstanceId: string | null;
	/** Когда владельца видели в последний раз. */
	ownerSeenAt: Date | null;
	/** Кто пришёл. */
	incomingInstanceId: string;
	now: Date;
	offlineAfterSecs: number;
}): InstanceDecision {
	const { ownerInstanceId, ownerSeenAt, incomingInstanceId, now, offlineAfterSecs } = input;
	if (!ownerInstanceId || ownerInstanceId === "") return { kind: "claim" };
	if (ownerInstanceId === incomingInstanceId) return { kind: "refresh" };

	// Владелец молчит дольше срока — его место свободно. Без этого перезапуск службы
	// (новый pid → новый идентификатор) навсегда закрывал бы агенту дорогу.
	const secsAgo = ownerSeenAt ? Math.floor((now.getTime() - ownerSeenAt.getTime()) / 1000) : Number.MAX_SAFE_INTEGER;
	if (secsAgo > offlineAfterSecs) return { kind: "claim" };

	return { kind: "reject", ownerInstanceId, ownerSeenSecsAgo: secsAgo };
}

/** Текст отказа для второго экземпляра — он попадёт в лог агента, а не в панель. */
export function instanceConflictMessage(ownerInstanceId: string, secsAgo: number): string {
	return `Под этим токеном уже работает другой экземпляр агента (${ownerInstanceId}, отвечал ${secsAgo} с назад). `
		+ "Одновременная работа двух процессов запрещена: они разбирают одну очередь команд, и "
		+ "при разошедшихся настройках команды отказывают через раз. Остановите лишний экземпляр "
		+ "или заведите отдельного агента со своим токеном («Администрирование 1С» → «Агенты» → «Создать»).";
}
